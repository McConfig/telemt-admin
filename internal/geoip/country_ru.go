package geoip

// CountryName возвращает русское название страны по коду ISO, а если его
// нет в словаре — английское название из базы, а если нет и его — сам код.
func CountryName(code, fallback string) string {
	if code == "" {
		return fallback
	}
	if name, ok := countryRU[code]; ok {
		return name
	}
	if fallback != "" {
		return fallback + " (" + code + ")"
	}
	return code
}

